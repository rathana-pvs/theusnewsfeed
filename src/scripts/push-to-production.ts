/**
 * Copy this machine's local CMS content (media files, categories, articles)
 * to a deployed site over HTTPS, using Payload's REST API. Authors are not
 * copied: articles arrive without an author.
 *
 * Usage:
 *   npx tsx --env-file=.env.local src/scripts/push-to-production.ts --dry-run
 *   PROD_EMAIL=you@example.com PROD_PASSWORD='...' \
 *     npx tsx --env-file=.env.local src/scripts/push-to-production.ts [--target=https://theusnewsfeed.com]
 *
 * The account must be an admin (or editor) on the target site.
 * Safe to re-run: categories and articles are matched by slug and
 * media by filename, so anything already on the target is reused, not duplicated.
 * Image sizes (thumbnail/card/hero) are regenerated by the target on upload.
 */
import fs from 'fs/promises'
import path from 'path'
import { getPayload } from 'payload'
import config from '../../payload.config'

const arg = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split('=')[1]
const TARGET = (arg('target') || 'https://theusnewsfeed.com').replace(/\/$/, '')
const DRY_RUN = process.argv.includes('--dry-run')
const MEDIA_DIR = path.resolve(process.cwd(), 'public/media')

// Fields the target sets itself; sending them would fail validation or be ignored.
const SYSTEM_KEYS = new Set(['id', 'createdAt', 'updatedAt', 'createdBy', 'sizes', 'url', 'thumbnailURL'])

let token = ''

async function api(method: string, route: string, body?: unknown | FormData): Promise<any> {
  const headers: Record<string, string> = {}
  if (token) headers.Authorization = `JWT ${token}`
  let payloadBody: BodyInit | undefined
  if (body instanceof FormData) payloadBody = body
  else if (body !== undefined) {
    headers['Content-Type'] = 'application/json'
    payloadBody = JSON.stringify(body)
  }
  // Reads retry on network errors. Writes don't (a retry could duplicate a
  // record); a failed write is reported and picked up by the next run.
  const attempts = method === 'GET' ? 4 : 1
  let res: Response | undefined
  for (let i = 1; ; i++) {
    try {
      res = await fetch(`${TARGET}/api${route}`, { method, headers, body: payloadBody })
      break
    } catch (err) {
      if (i >= attempts) throw err
      await new Promise((r) => setTimeout(r, 1000 * i))
    }
  }
  const text = await res.text()
  let json: any
  try {
    json = JSON.parse(text)
  } catch {
    json = { raw: text.slice(0, 300) }
  }
  if (!res.ok) {
    const detail = json?.errors?.map((e: any) => e.message + (e.data ? ` ${JSON.stringify(e.data)}` : '')).join('; ')
    throw new Error(`${method} ${route} -> ${res.status} ${detail || json.raw || ''}`)
  }
  return json
}

async function findOne(collection: string, field: string, value: string): Promise<any | null> {
  const q = `?where[${field}][equals]=${encodeURIComponent(value)}&limit=1&depth=0`
  const { docs } = await api('GET', `/${collection}${q}`)
  return docs[0] || null
}

function strip(doc: Record<string, any>): Record<string, any> {
  const out: Record<string, any> = {}
  for (const [k, v] of Object.entries(doc)) {
    if (SYSTEM_KEYS.has(k) || v === null || v === undefined) continue
    // Rich text is copied verbatim: its nodes legitimately carry ids and nulls.
    if (k === 'content') out[k] = v
    else if (Array.isArray(v)) out[k] = v.map((item) => (item && typeof item === 'object' ? strip(item) : item))
    else if (v && typeof v === 'object' && !(v instanceof Date)) out[k] = strip(v)
    else out[k] = v
  }
  return out
}

const idOf = (v: any) => (v && typeof v === 'object' ? v.id : v)

async function main() {
  const payload = await getPayload({ config })
  const all = async (collection: any) =>
    (await payload.find({ collection, limit: 10000, depth: 0, pagination: false, sort: 'id' })).docs as any[]

  const [media, categories, articles] = await Promise.all([all('media'), all('categories'), all('articles')])
  console.log(`Local: ${media.length} media, ${categories.length} categories, ${articles.length} articles`)
  console.log(`Target: ${TARGET}${DRY_RUN ? '  (dry run: nothing will be written)' : ''}\n`)

  // Only push media something actually uses.
  const usedMedia = new Set<number>()
  for (const a of articles) {
    for (const ref of [a.coverImage, a.og?.ogImage, a.meta?.image]) if (ref) usedMedia.add(idOf(ref))
  }
  const mediaToPush = media.filter((m) => usedMedia.has(m.id))

  // Fail early on missing files instead of halfway through.
  const missing: string[] = []
  let bytes = 0
  for (const m of mediaToPush) {
    try {
      bytes += (await fs.stat(path.join(MEDIA_DIR, m.filename))).size
    } catch {
      missing.push(m.filename)
    }
  }
  console.log(`Media to upload: ${mediaToPush.length} files, ${(bytes / 1048576).toFixed(1)} MB`)
  if (missing.length) throw new Error(`Missing local files in public/media: ${missing.join(', ')}`)

  if (DRY_RUN) {
    let existing = 0
    for (const a of articles) if (await findOne('articles', 'slug', a.slug)) existing++
    console.log(`Articles already on target (public, published only): ${existing}/${articles.length}`)
    console.log('\nDry run OK. Re-run without --dry-run and with PROD_EMAIL / PROD_PASSWORD set.')
    process.exit(0)
  }

  const email = process.env.PROD_EMAIL
  const password = process.env.PROD_PASSWORD
  if (!email || !password) throw new Error('Set PROD_EMAIL and PROD_PASSWORD for an admin account on the target.')
  const login = await api('POST', '/users/login', { email, password })
  token = login.token
  console.log(`Logged in as ${login.user?.email} (${login.user?.role})\n`)

  const counts = { created: 0, reused: 0, failed: 0 }
  const failures: string[] = []

  // 1. Media
  const mediaMap = new Map<number, number>()
  for (const m of mediaToPush) {
    try {
      const existing = await findOne('media', 'filename', m.filename)
      if (existing) {
        mediaMap.set(m.id, existing.id)
        counts.reused++
        console.log(`↷ media ${m.filename}`)
        continue
      }
      const file = await fs.readFile(path.join(MEDIA_DIR, m.filename))
      const form = new FormData()
      form.append('file', new Blob([file], { type: m.mimeType }), m.filename)
      form.append(
        '_payload',
        JSON.stringify({ alt: m.alt, caption: m.caption, source: m.source, externalUrl: m.externalUrl }),
      )
      const { doc } = await api('POST', '/media', form)
      mediaMap.set(m.id, doc.id)
      counts.created++
      console.log(`✓ media ${m.filename}`)
    } catch (err: any) {
      counts.failed++
      failures.push(`media ${m.filename}: ${err.message}`)
      console.error(`✗ media ${m.filename}: ${err.message}`)
    }
  }
  const mapMedia = (ref: any) => (ref ? mediaMap.get(idOf(ref)) : undefined)

  // 2. Categories, matched by slug.
  async function pushBySlug(collection: string, docs: any[], prepare: (d: any) => any) {
    const map = new Map<number, number>()
    for (const d of docs) {
      try {
        const existing = await findOne(collection, 'slug', d.slug)
        if (existing) {
          map.set(d.id, existing.id)
          counts.reused++
          console.log(`↷ ${collection} ${d.slug}`)
          continue
        }
        const { doc } = await api('POST', `/${collection}`, prepare(strip(d)))
        map.set(d.id, doc.id)
        counts.created++
        console.log(`✓ ${collection} ${d.slug}`)
      } catch (err: any) {
        counts.failed++
        failures.push(`${collection} ${d.slug}: ${err.message}`)
        console.error(`✗ ${collection} ${d.slug}: ${err.message}`)
      }
    }
    return map
  }

  const categoryMap = await pushBySlug('categories', categories, (d) => d)

  // 3. Articles, oldest first so IDs follow publish order.
  const ordered = [...articles].sort(
    (a, b) => new Date(a.publishedAt || a.createdAt).getTime() - new Date(b.publishedAt || b.createdAt).getTime(),
  )
  for (const a of ordered) {
    try {
      const existing = await findOne('articles', 'slug', a.slug)
      if (existing) {
        counts.reused++
        console.log(`↷ article ${a.slug}`)
        continue
      }
      const data = strip(a)
      data.coverImage = mapMedia(a.coverImage)
      if (!data.coverImage) throw new Error('cover image was not uploaded')
      if (data.og) data.og.ogImage = mapMedia(a.og?.ogImage)
      if (data.meta) data.meta.image = mapMedia(a.meta?.image)
      data.category = a.category ? categoryMap.get(idOf(a.category)) : undefined
      // Authors are not copied; articles go up without one.
      delete data.author
      await api('POST', '/articles', data)
      counts.created++
      console.log(`✓ article ${a.slug}`)
    } catch (err: any) {
      counts.failed++
      failures.push(`article ${a.slug}: ${err.message}`)
      console.error(`✗ article ${a.slug}: ${err.message}`)
    }
  }

  console.log(`\nDone: ${counts.created} created, ${counts.reused} already there, ${counts.failed} failed.`)
  if (failures.length) console.log('Failures:\n  ' + failures.join('\n  '))
  process.exit(failures.length ? 1 : 0)
}

main().catch((err) => {
  console.error(err.message || err)
  process.exit(1)
})
